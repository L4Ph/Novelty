/// 禁則処理のためのユーティリティクラス
class Kinsoku {
  Kinsoku._();

  /// 行頭禁則文字かどうかを判定する
  ///
  /// 列の先頭に来てはいけない文字
  static bool isHeadProhibited(String char) {
    return _headProhibited.contains(char);
  }

  /// 行末禁則文字かどうかを判定する
  ///
  /// 列の末尾に来てはいけない文字
  static bool isTailProhibited(String char) {
    return _tailProhibited.contains(char);
  }

  /// 行頭禁則文字
  ///
  /// 字形変換前の文字（例: 。）と縦書き変体（例: ︒）の両方を含める。
  static const _headProhibited = <String>{
    // 句読点
    '。',
    '、',
    '．',
    '，',
    '：',
    '；',
    // 縦書き変体の句読点
    '︒', // 。の縦書き変体
    '︑', // 、の縦書き変体
    '︓', // ：の縦書き変体
    '︔', // ；の縦書き変体
    // 疑問符・感嘆符
    '？',
    '！',
    '?',
    '!',
    '︖', // ？の縦書き変体
    '︕', // ！の縦書き変体
    // 閉じ括弧
    '）',
    '］',
    '｝',
    '」',
    '』',
    '】',
    '〉',
    '》',
    ')',
    ']',
    '}',
    // 縦書き変体の閉じ括弧
    '︶', // ）の縦書き変体
    '﹈', // ］の縦書き変体
    '︸', // ｝の縦書き変体
    '﹂', // 」の縦書き変体
    '﹄', // 』の縦書き変体
    '︼', // 】の縦書き変体
    '︾', // 》の縦書き変体
    '﹀', // ＞の縦書き変体
    // 長音・波線
    'ー',
    '～',
    '〜',
    '丨', // 長音の縦書き変体
    // 三点リーダ
    '…',
    '‥',
    '︙', // …の縦書き変体
    '︰', // ‥の縦書き変体
  };

  /// 行末禁則文字
  ///
  /// 字形変換前の文字（例: （）と縦書き変体（例: ︵）の両方を含める。
  static const _tailProhibited = <String>{
    // 開き括弧
    '（',
    '［',
    '｛',
    '「',
    '『',
    '【',
    '〈',
    '《',
    '(',
    '[',
    '{',
    // 縦書き変体の開き括弧
    '︵', // （の縦書き変体
    '﹇', // ［の縦書き変体
    '︷', // ｛の縦書き変体
    '﹁', // 「の縦書き変体
    '﹃', // 『の縦書き変体
    '︻', // 【の縦書き変体
    '︿', // 〈の縦書き変体
    '︽', // 《の縦書き変体
  };
}
