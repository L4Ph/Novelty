/// 最小 NFC: 濁点・半濁点の結合文字を直前の基底文字と合成する。
/// 既に合成済みの文字はそのまま。完全な Unicode NFC 表は埋め込まない。
///
/// 正準等価の合成は結合文字が独立したコードポイントとして並ぶ段階でしか
/// 検出できないため、生のコードポイント列に対して行う。
String nfcNormalize(String text) {
  final runes = text.runes.toList();
  if (runes.length < 2) return text;

  final out = <int>[];
  for (var i = 0; i < runes.length; i++) {
    final code = runes[i];
    // 結合文字 (濁点/半濁点)が単独で現れたら直前の基底文字と合成する。
    // 合成結果が基底文字と同一 (既に濁音化済み等) の場合は合成せず、
    // 結合文字を独立した1文字として残す (JS の NFC と同じ振る舞い)。
    if ((code == 0x3099 || code == 0x309A) && out.isNotEmpty) {
      final composed = _voiced[out.last]?[code];
      if (composed != null && composed != out.last) {
        out[out.length - 1] = composed;
        continue;
      }
    }
    out.add(code);
  }
  return String.fromCharCodes(out);
}

